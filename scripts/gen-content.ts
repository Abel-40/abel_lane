/**
 * Generates typed content modules in src/content/ from the kit's reference data.
 *   reference/content.json → projects, experience, history, stack, rules, journey, marquee, hero-console
 *   src/content/case-studies.json → cases (the write-ups, edited by hand)
 *   reference/icons.json   → icons
 * Run with `pnpm gen:content`. Output files are committed; never edit them by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { caseFile } from "../src/content/case-schema";

const root = process.cwd();
const content = JSON.parse(readFileSync(join(root, "reference/content.json"), "utf8"));
const icons = JSON.parse(readFileSync(join(root, "reference/icons.json"), "utf8"));
// Images add-on kit: project screens (text used verbatim, PROMPT §3 / §6). Case figures now live in case-studies.json.
const screens = JSON.parse(readFileSync(join(root, "kits/images/data/project-screens.json"), "utf8"));
const shotOf = (sh: Record<string, unknown>) => ({
  file: sh.file,
  label: sh.label,
  theme: sh.theme,
  caption: sh.caption,
  alt: sh.alt,
  src: sh.src,
  srcSm: sh.srcSm,
  width: sh.width,
  height: sh.height,
});
const outDir = join(root, "src/content");

const SLUGS: Record<string, string> = {
  insight: "insight-stream",
  mood: "moodverse",
  seo: "seo-maker",
  alert: "alertchain",
  work: "workroom",
};

const HEADER =
  "/* Generated by scripts/gen-content.ts (reference/*.json, src/content/case-studies.json). Do not edit by hand. */\n";

function emit(file: string, imports: string, body: string) {
  writeFileSync(join(outDir, file), `${HEADER}${imports ? imports + "\n\n" : "\n"}${body}\n`);
  console.log("wrote src/content/" + file);
}

const json = (v: unknown) => JSON.stringify(v, null, 2);

/** A project link is null (not supplied yet) or an absolute https URL. */
function linkOf(id: string, key: string, v: unknown): string | null {
  if (v == null) return null;
  if (typeof v !== "string" || !/^https:\/\/\S+$/.test(v)) throw new Error(`projects.${id}.links.${key} must be null or an https URL`);
  return v;
}

/* ---------- projects ---------- */
type RawProject = Record<string, unknown> & { id: string; stack: [string, string[]][] };
const projects = (content.projects as RawProject[]).map((p) => {
  const img = (screens.projects as { id: string; hue: string[]; cover: object; shots: Record<string, unknown>[] }[]).find((x) => x.id === p.id);
  if (!img) throw new Error(`no screens for project ${p.id}`);
  return {
  id: p.id,
  slug: SLUGS[p.id],
  num: p.num,
  name: p.name,
  tagline: p.tagline,
  links: {
    live: linkOf(p.id, "live", (p.links as Record<string, unknown> | undefined)?.live),
    repo: linkOf(p.id, "repo", (p.links as Record<string, unknown> | undefined)?.repo),
  },
  hue: img.hue,
  cover: img.cover,
  shots: img.shots.map(shotOf),
  cats: p.cats,
  kindLabel: p.kindLabel,
  caseId: p.caseId,
  status: p.status ?? null,
  role: p.role ?? null,
  hook: p.hook,
  meet: p.meet,
  what: p.what,
  features: p.features,
  chips: p.chips,
  flow: p.flow,
  stack: p.stack.map(([label, items]) => ({ label, items })),
  };
});
emit(
  "projects.ts",
  'import type { Project } from "./types";',
  `export const projects: readonly Project[] = ${json(projects)};`,
);

/* ---------- case studies (source: src/content/case-studies.json) ---------- */
const caseFileData = caseFile.parse(JSON.parse(readFileSync(join(root, "src/content/case-studies.json"), "utf8")));
const cases = caseFileData.cases
  .map((c) => {
    const { widthSm: _w, heightSm: _h, ...figure } = c.figure as Record<string, unknown>;
    void _w;
    void _h;
    return { ...c, slug: SLUGS[c.id], figure };
  })
  .sort((a, b) => a.num.localeCompare(b.num));
emit(
  "cases.ts",
  'import type { CaseStudy } from "./types";',
  `export const cases: readonly CaseStudy[] = ${json(cases)};`,
);

/* ---------- experience (home timeline) ---------- */
const experience = (content.xp as [string, string, string, string, string, string[]][]).map(
  ([period, role, org, note, year, chips], i) => ({ period, role, org, note, year, chips, current: i === 0 }),
);
emit(
  "experience.ts",
  'import type { ExperienceItem } from "./types";',
  `export const experience: readonly ExperienceItem[] = ${json(experience)};`,
);

/* ---------- career history (about log) ---------- */
emit(
  "history.ts",
  'import type { HistoryItem } from "./types";',
  `export const history: readonly HistoryItem[] = ${json(content.history)};`,
);

/* ---------- tool stack ---------- */
const stack = (content.stack as [string, string, [string, string][]][]).map(([id, label, tools]) => ({
  id,
  label,
  tools: tools.map(([name, icon]) => ({ name, icon })),
}));
emit(
  "stack.ts",
  'import type { ToolGroup } from "./types";',
  `export const toolGroups: readonly ToolGroup[] = ${json(stack)};`,
);

/* ---------- principles ---------- */
const rules = (content.rules as [string, string, string, string, [string, string][]][]).map(
  ([icon, title, desc, proof, tags]) => ({
    icon,
    title,
    desc,
    proof,
    tags: (tags ?? []).map(([label, target]) => ({ label, target })),
  }),
);
emit("rules.ts", 'import type { Rule } from "./types";', `export const rules: readonly Rule[] = ${json(rules)};`);

/* ---------- request journey ---------- */
emit(
  "journey.ts",
  'import type { JourneyNode, JourneyStage } from "./types";',
  `export const journeyStages: readonly JourneyStage[] = ${json(content.journey)};\n\n` +
    `export const journeyNodes: readonly JourneyNode[] = ${json(content.jnodes)};`,
);

/* ---------- marquee ---------- */
emit(
  "marquee.ts",
  "",
  `export const marqueeRows: readonly (readonly string[])[] = ${json(content.marquee)};`,
);

/* ---------- hero console ---------- */
const hc = content.heroConsole;
emit(
  "hero-console.ts",
  'import type { ConsoleScenario } from "./types";',
  `/** ${hc._note} */\n` +
    `export const consoleScenarios: readonly ConsoleScenario[] = ${json(hc.scenarios)} as const;\n\n` +
    `export const rotatingWords: readonly string[] = ${json(hc.rotatingWords)};\n\n` +
    `/** Brand keys for the logo chips under the hero console. */\n` +
    `export const heroStackChips: readonly string[] = ${json(hc.stackChips)};`,
);

/* ---------- icons ---------- */
const uiKeys = Object.keys(icons.ui);
const genKeys = Object.keys(icons.generic);
emit(
  "icons.ts",
  'import type { BrandIcon } from "./types";',
  `/** ${icons._note} */\n\n` +
    `export const uiIcons = ${json(icons.ui)} as const;\n` +
    `export type UiIconKey = ${uiKeys.map((k) => JSON.stringify(k)).join(" | ")};\n\n` +
    `export const genericIcons = ${json(icons.generic)} as const;\n` +
    `export type GenericIconKey = ${genKeys.map((k) => JSON.stringify(k)).join(" | ")};\n\n` +
    `export const brandIcons: Record<string, BrandIcon> = ${json(icons.brands)};`,
);
