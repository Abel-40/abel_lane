/**
 * Generates typed content modules in src/content/ from the hand-edited files in data/:
 *   data/projects.json     → projects
 *   data/case-studies.json → cases (validated with Zod, src/content/case-schema.ts)
 *   data/about.json        → about (hero, facts, education), experience, history, stack
 *   data/home.json         → hero-console, rules, journey, marquee
 *   data/icons.json        → icons
 * data/site.json is imported directly by src/content/site.ts.
 * Runs before every build (`prebuild`) and on `pnpm gen:content`. Never edit the output by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { caseFile } from "../src/content/case-schema";

const root = process.cwd();
const read = (file: string) => JSON.parse(readFileSync(join(root, "data", file), "utf8"));
const projectsData = read("projects.json");
const about = read("about.json");
const home = read("home.json");
const icons = read("icons.json");
const outDir = join(root, "src/content");

const SLUGS: Record<string, string> = {
  insight: "insight-stream",
  mood: "moodverse",
  seo: "seo-maker",
  alert: "alertchain",
  work: "workroom",
};

const HEADER = "/* Generated by scripts/gen-content.ts from data/*.json. Do not edit by hand; edit the JSON. */\n";

function emit(file: string, imports: string, body: string) {
  writeFileSync(join(outDir, file), `${HEADER}${imports ? imports + "\n\n" : "\n"}${body}\n`);
  console.log("wrote src/content/" + file);
}

const json = (v: unknown) => JSON.stringify(v, null, 2);

/** A project link is null (not supplied yet) or an absolute https URL. */
function linkOf(id: string, key: string, v: unknown): string | null {
  if (v == null || v === "") return null;
  if (typeof v !== "string" || !/^https:\/\/\S+$/.test(v)) throw new Error(`projects.${id}.links.${key} must be null or an https URL`);
  return v;
}

/* ---------- projects ---------- */
type RawProject = Record<string, unknown> & {
  id: string;
  links?: { live?: unknown; repo?: unknown };
  images: { hue: string[]; cover: object; shots: object[] };
};
const projects = (projectsData.projects as RawProject[]).map((p) => {
  if (!SLUGS[p.id]) throw new Error(`unknown project id ${p.id}`);
  return {
    id: p.id,
    slug: SLUGS[p.id],
    num: p.num,
    name: p.name,
    tagline: p.tagline,
    links: { live: linkOf(p.id, "live", p.links?.live), repo: linkOf(p.id, "repo", p.links?.repo) },
    hue: p.images.hue,
    cover: p.images.cover,
    shots: p.images.shots,
    cats: p.cats,
    kindLabel: p.kindLabel,
    caseId: p.caseId,
    status: p.status ?? null,
    role: p.role ?? null,
    hook: p.hook,
    meet: p.meet,
    what: p.what,
    features: p.features,
    chips: p.chips,
    flow: p.flow,
    stack: p.stack,
  };
});
emit("projects.ts", 'import type { Project } from "./types";', `export const projects: readonly Project[] = ${json(projects)};`);

/* ---------- case studies ---------- */
const cases = caseFile
  .parse(read("case-studies.json"))
  .cases.map((c) => {
    const { widthSm: _w, heightSm: _h, ...figure } = c.figure as Record<string, unknown>;
    void _w;
    void _h;
    return { ...c, slug: SLUGS[c.id], figure };
  })
  .sort((a, b) => a.num.localeCompare(b.num));
emit("cases.ts", 'import type { CaseStudy } from "./types";', `export const cases: readonly CaseStudy[] = ${json(cases)};`);

/* ---------- about ---------- */
emit(
  "about.ts",
  'import type { AboutContent } from "./types";',
  `export const aboutContent: AboutContent = ${json({ hero: about.hero, facts: about.facts, education: about.education })};`,
);
emit(
  "experience.ts",
  'import type { ExperienceItem } from "./types";',
  `export const experience: readonly ExperienceItem[] = ${json(about.experience)};`,
);
emit("history.ts", 'import type { HistoryItem } from "./types";', `export const history: readonly HistoryItem[] = ${json(about.careerLog)};`);
emit("stack.ts", 'import type { ToolGroup } from "./types";', `export const toolGroups: readonly ToolGroup[] = ${json(about.tools)};`);

/* ---------- home ---------- */
emit("rules.ts", 'import type { Rule } from "./types";', `export const rules: readonly Rule[] = ${json(home.principles)};`);
emit(
  "journey.ts",
  'import type { JourneyNode, JourneyStage } from "./types";',
  `export const journeyStages: readonly JourneyStage[] = ${json(home.journey.stages)};\n\n` +
    `export const journeyNodes: readonly JourneyNode[] = ${json(home.journey.nodes)};`,
);
emit("marquee.ts", "", `export const marqueeRows: readonly (readonly string[])[] = ${json(home.marquee)};`);
const hc = home.heroConsole;
emit(
  "hero-console.ts",
  'import type { ConsoleScenario } from "./types";',
  `/** ${hc._note} */\n` +
    `export const consoleScenarios: readonly ConsoleScenario[] = ${json(hc.scenarios)} as const;\n\n` +
    `export const rotatingWords: readonly string[] = ${json(hc.rotatingWords)};\n\n` +
    `/** Brand keys for the logo chips under the hero console. */\n` +
    `export const heroStackChips: readonly string[] = ${json(hc.stackChips)};`,
);

/* ---------- icons ---------- */
const uiKeys = Object.keys(icons.ui);
const genKeys = Object.keys(icons.generic);
emit(
  "icons.ts",
  'import type { BrandIcon } from "./types";',
  `/** ${icons._note} */\n\n` +
    `export const uiIcons = ${json(icons.ui)} as const;\n` +
    `export type UiIconKey = ${uiKeys.map((k) => JSON.stringify(k)).join(" | ")};\n\n` +
    `export const genericIcons = ${json(icons.generic)} as const;\n` +
    `export type GenericIconKey = ${genKeys.map((k) => JSON.stringify(k)).join(" | ")};\n\n` +
    `export const brandIcons: Record<string, BrandIcon> = ${json(icons.brands)};`,
);
