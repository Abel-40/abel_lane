import { chromium } from "@playwright/test";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto("http://localhost:3000/projects", { waitUntil: "networkidle" }); await p.waitForTimeout(3500);
await p.locator(".pcard").nth(0).click(); await p.waitForTimeout(1800);
const st = async (l) => console.log(l, "| url", new URL(p.url()).pathname, "| dialog", await p.locator('[role=dialog]').count(), "| name", await p.locator("#poName").first().textContent().catch(() => "-"), "| focus", await p.evaluate(() => document.activeElement?.id || document.activeElement?.className));
await st("open");
await p.getByRole("button", { name: "Next project" }).click(); await p.waitForTimeout(1200); await st("next");
await p.getByRole("button", { name: "Previous project" }).click(); await p.waitForTimeout(1200); await st("prev");
await p.keyboard.press("Escape"); await p.waitForTimeout(1300); await st("esc");
await p.locator(".pcard").nth(2).click(); await p.waitForTimeout(1800); await st("open2");
await p.goBack(); await p.waitForTimeout(1000); await st("back");
await p.goForward(); await p.waitForTimeout(1200); await st("fwd");
await p.locator(".crumb-link").click(); await p.waitForTimeout(1500); await st("crumb on /projects");
await p.goto("http://localhost:3000/", { waitUntil: "networkidle" }); await p.waitForTimeout(2500);
await p.locator(".wcard .btn").first().scrollIntoViewIfNeeded(); await p.waitForTimeout(800);
await p.evaluate(() => document.querySelector(".wcard .btn").click()); await p.waitForTimeout(1800); await st("from home");
await p.locator(".crumb-link").click(); await p.waitForTimeout(2500); await st("crumb from home");
await p.goto("http://localhost:3000/projects/seo-maker", { waitUntil: "networkidle" }); await p.waitForTimeout(1500); await st("deep link");
await p.getByRole("button", { name: "Next project" }).click(); await p.waitForTimeout(1200); await st("deep next");
console.log("ERRORS", errs);
await b.close();
