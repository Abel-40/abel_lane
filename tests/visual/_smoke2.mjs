import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
p.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errors.push(m.type() + ": " + m.text()); });
p.on("pageerror", (e) => errors.push("pageerror: " + e.message));
await p.goto("http://localhost:3000/", { waitUntil: "networkidle" });
await p.waitForTimeout(400);
await p.screenshot({ path: "qa/shots/p2-loader.jpg", quality: 70 });
await p.waitForTimeout(2600);
console.log("loader present:", await p.locator("#loader").count(), "data-loader:", await p.evaluate(() => document.documentElement.dataset.loader));
await p.screenshot({ path: "qa/shots/p2-home.jpg", quality: 70 });
await p.click("nav.links >> text=About");
await p.waitForTimeout(700);
await p.screenshot({ path: "qa/shots/p2-shutter.jpg", quality: 70 });
await p.waitForTimeout(1200);
console.log("url:", p.url(), "focused:", await p.evaluate(() => document.activeElement?.tagName + " " + document.activeElement?.textContent));
console.log("active link:", await p.locator(".link.on").textContent());
await p.goBack(); await p.waitForTimeout(900);
console.log("after back url:", p.url(), "focused:", await p.evaluate(() => document.activeElement?.tagName));
await p.screenshot({ path: "qa/shots/p2-back.jpg", quality: 70 });
await p.setViewportSize({ width: 390, height: 844 });
await p.waitForTimeout(300);
await p.click("#menuBtn"); await p.waitForTimeout(1000);
await p.screenshot({ path: "qa/shots/p2-menu.jpg", quality: 70 });
await p.click(".menu-link >> text=Contact"); await p.waitForTimeout(2000);
console.log("menu hidden:", await p.locator("#menu").getAttribute("hidden"), "url:", p.url());
console.log("ERRORS:\n" + errors.join("\n"));
await b.close();
