import { chromium } from "@playwright/test";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => (m.type() === "error" || m.type()==="warning") && errs.push(m.text().slice(0,200)));
await p.goto("http://localhost:3000/case-studies/moodverse", { waitUntil: "networkidle" }); await p.waitForTimeout(4000);
console.log("direct:", await p.evaluate(() => [...document.querySelectorAll(".rd-in")].map(e => getComputedStyle(e).opacity + "/" + getComputedStyle(e).visibility).join(" ")));
await p.goto("http://localhost:3000/case-studies", { waitUntil: "networkidle" }); await p.waitForTimeout(3000);
await p.locator(".cs-row-btn").first().click(); await p.waitForTimeout(3500);
console.log("nav:", await p.evaluate(() => [...document.querySelectorAll(".rd-in")].map(e => getComputedStyle(e).opacity + "/" + getComputedStyle(e).visibility + "/" + e.getAttribute("style")).join(" | ")));
console.log(errs);
await b.close();
