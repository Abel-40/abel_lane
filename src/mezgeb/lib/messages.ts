/** Same seed, same message: a stable pick (e.g. one per day) that still varies across days and events. */
export function pickMessage(list: readonly string[], seed: string): string {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return list[(h >>> 0) % list.length];
}
